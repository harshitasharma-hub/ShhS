#!/usr/bin/env python3
"""Copy the real scores from ../runs/*/metrics.json into src/results.js, so the talk shows what was measured.

  python3 tools/sync_results.py
  npm run build

A bar in the Evidence chart is filled only when a run exists for it. Everything else stays an empty
outline with a question mark. The numbers are copied as they are: nothing here is typed by hand.

How a run is sorted:
  zero-shot       the name starts with "zeroshot"
  real only       no synthetic manifest, fraction 10, 25, 50 or 100 (percent of the BRACOL train photos)
  renders + real  a synthetic manifest and fraction above 0
  renders only    a synthetic manifest and fraction 0
Several seeds of the same arm and fraction are averaged. The interval is the widest one of the seeds.
"""
import glob
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
RUNS = HERE.parent / "runs"
OUT = HERE / "src" / "results.js"


def arm_of(m):
    if str(m.get("name", "")).startswith("zeroshot"):
        return "zeroShot", 0
    if not m.get("synthetic_manifest"):
        return "real", int(m.get("fraction", 100))
    return ("syn" if int(m.get("fraction", 0)) == 0 else "mix"), int(m.get("fraction", 0))


def main():
    runs = []
    for f in sorted(glob.glob(str(RUNS / "*" / "metrics.json"))):
        m = json.load(open(f))
        t = m.get("test", {})
        if t.get("n", 0) < 100:        # a smoke test on a handful of photos is not a result
            continue
        arm, frac = arm_of(m)
        ns = m.get("not_sure", {}).get("test", {})
        sev = t.get("rust_sensitivity_by_severity", {})
        runs.append(dict(arm=arm, frac=frac, name=m.get("name"), seed=m.get("seed", 0), n=t["n"], auc=t["auc"], lo=t["auc_ci95"][0], hi=t["auc_ci95"][1],
                         accuracy=t["accuracy"], sensitivity=t["sensitivity"], specificity=t["specificity"],
                         sev1=sev.get("1", {}).get("sensitivity"), sev1n=sev.get("1", {}).get("n"),
                         answered=ns.get("coverage"), answeredAccuracy=ns.get("accuracy_answered")))
    groups = {}
    for r in runs:
        groups.setdefault((r["arm"], r["frac"]), []).append(r)

    def mean(rs, k):
        v = [r[k] for r in rs if r[k] is not None]
        return round(statistics.mean(v), 4) if v else None

    def pack(rs):
        return dict(runs=len(rs), n=rs[0]["n"], auc=mean(rs, "auc"), lo=round(min(r["lo"] for r in rs), 4), hi=round(max(r["hi"] for r in rs), 4),
                    accuracy=mean(rs, "accuracy"), sensitivity=mean(rs, "sensitivity"), specificity=mean(rs, "specificity"),
                    sev1=mean(rs, "sev1"), sev1n=rs[0]["sev1n"], answered=mean(rs, "answered"), answeredAccuracy=mean(rs, "answeredAccuracy"),
                    names=[r["name"] for r in rs])

    res = {"testN": 261, "zeroShot": None, "real": {}, "mix": {}, "syn": {}}
    for (arm, frac), rs in groups.items():
        if arm == "zeroShot":
            res["zeroShot"] = pack(rs)
        else:
            res[arm][str(frac)] = pack(rs)
    body = json.dumps(res, indent=2)
    OUT.write_text("// Generated by tools/sync_results.py from ../runs/*/metrics.json. Do not edit by hand.\n"
                   "// Each entry is a measured score on the 261 locked BRACOL test leaves. Missing entries are not measured yet.\n"
                   f"export const RESULTS = {body};\n")
    print(f"{len(runs)} run(s) copied to {OUT.relative_to(HERE)}")
    for (arm, frac), rs in sorted(groups.items()):
        print(f"  {arm:8} {frac:>3}%  AUC {mean(rs, 'auc')}  ({len(rs)} run)")


if __name__ == "__main__":
    main()
